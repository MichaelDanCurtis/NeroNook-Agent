const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { titleMatches } = require('../Resources/Views/chat/chat-history.js');
assert.ok(titleMatches('Design review', 'REVIEW'));
assert.ok(titleMatches('Café planning 🌿', 'cafe'));
assert.ok(titleMatches('Café planning 🌿', '🌿'));
assert.ok(titleMatches('東京の会議', '東京'));
assert.ok(titleMatches('A [draft].*', '[draft].*'));
assert.ok(!titleMatches('Another chat', '<script>'));
assert.ok(!titleMatches('Team lunch', 'review'));
assert.ok(titleMatches('Anything', '  '));

const nodes = new Map();
const node = id => { if (!nodes.has(id)) nodes.set(id, { hidden:false, value:'', textContent:'', children:[], addEventListener(name,fn){this[name]=fn}, focus(){this.focused=true} }); return nodes.get(id); };
let observe, keydown;
const context = { document:{getElementById:node,addEventListener(name,fn){if(name==='keydown')keydown=fn}}, MutationObserver:class {constructor(fn){observe=fn} observe(){} } };
vm.runInNewContext(fs.readFileSync(require.resolve('../Resources/Views/chat/chat-history.js'),'utf8'),context);
assert.equal(node('historyResult').textContent,'No saved conversations yet.');
const first={tagName:'BUTTON',textContent:'Café project',disabled:true,onclick(){this.clicked=true}}, second={tagName:'BUTTON',textContent:'Weekend plans',disabled:false};
node('conversations').children=[first,second]; observe();
assert.equal(node('historyResult').textContent,'2 conversations');
node('historyQuery').value='cafe'; node('historyQuery').input();
assert.equal(first.hidden,false); assert.equal(second.hidden,true); assert.equal(first.disabled,true);
assert.equal(node('historyResult').textContent,'1 of 2 conversations');
node('historyQuery').value='missing'; node('historyQuery').input();
assert.equal(node('historyResult').textContent,'No conversations match. Try another title.');
node('historyClear').onclick();
assert.ok(!first.hidden&&!second.hidden&&node('historyQuery').focused);
first.onclick(); assert.equal(first.clicked,true); // Filtering retained original handlers.
node('historyQuery').value='New'; node('historyQuery').input();
node('conversations').children.push({tagName:'BUTTON',textContent:'New arrival'}); observe();
assert.equal(node('historyResult').textContent,'1 of 3 conversations');
node('chatFind').hidden=true; node('history').hidden=false;
let prevented=false; keydown({key:'Escape',preventDefault(){prevented=true}});
assert.ok(prevented&&node('history').hidden&&node('historyButton').focused);
node('history').hidden=false; keydown({key:'Escape',defaultPrevented:true,preventDefault(){throw Error('Earlier Find handler already consumed Escape')}}); assert.equal(node('history').hidden,false);
node('chatFind').hidden=false; node('history').hidden=false;
keydown({key:'Escape',preventDefault(){throw Error('Find must own Escape while open')}});
assert.equal(node('history').hidden,false);
console.log('Conversation title filter: matcher, empty/no-match, clear, refresh, preserved handlers/disabled state and Escape checks passed.');
